#!/usr/bin/env python3
"""Measure every gate arm and regenerate `Docs/GATE_METRICS.md`.

The gate's numbers live in one generated document so no hand-edited copy can
drift from what the arms actually do. `./run.sh metrics` is the only supported
way to update them.
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

# Arms in the order the gate runs them. "blocking" arms are what `./run.sh all`
# and CI execute; the two strict arms are known red and reported separately.
ARMS = (
    ("fast", "blocking", "credential-free harness subsets (unit, integration, validation)"),
    ("build", "blocking", "DE production build + knowledge-base assertion"),
    ("website", "blocking", "Next.js production build"),
    ("docs", "blocking", "relative Markdown link/anchor check"),
    ("gnn", "blocking", "pinned GNN parser conformance"),
    ("lint", "strict", "ESLint over DE/"),
    ("types", "strict", "tsc -b over DE/"),
)

FAILED_COUNT = re.compile(r"Failed:\s*(\d+)")
LINT_SUMMARY = re.compile(r"(\d+) problems \((\d+) errors?, (\d+) warnings?\)")
TSC_ERROR = re.compile(r"error TS\d+")
FINAL_SUMMARY = re.compile(r"(checked \d+ relative links|docs links:|gnn-version|\"result\")")


def tool_version(command: list[str]) -> str:
    try:
        result = subprocess.run(command, capture_output=True, text=True, check=False, timeout=60)
    except (OSError, subprocess.SubprocessError):
        return "unavailable"
    text = (result.stdout or result.stderr).strip().splitlines()
    return text[0].strip() if text else "unavailable"


def count_tests(log: str) -> dict[str, int]:
    counts: dict[str, int] = {}
    current = None
    for line in log.splitlines():
        suite = re.search(r"(Unit|Integration|Validation|LLM) Tests:\s*$", line)
        if suite:
            current = suite.group(1).lower()
            continue
        total = re.match(r"^\s*Tests:\s*(\d+)\s*$", line)
        if total and current:
            counts[current] = int(total.group(1))
            current = None
    return counts


def run_arm(arm: str, root: Path, log_dir: Path) -> dict[str, object]:
    started = time.monotonic()
    result = subprocess.run(
        [str(root / "run.sh"), arm],
        cwd=root,
        capture_output=True,
        text=True,
        check=False,
    )
    elapsed = time.monotonic() - started
    log = result.stdout + result.stderr
    log_dir.mkdir(parents=True, exist_ok=True)
    (log_dir / f"{arm}.log").write_text(log, encoding="utf-8")

    record: dict[str, object] = {
        "arm": arm,
        "seconds": round(elapsed, 2),
        "exit": result.returncode,
        "log": (log_dir / f"{arm}.log"),
    }
    if arm == "fast":
        record["tests"] = count_tests(log)
        failures = [int(m) for m in FAILED_COUNT.findall(log)]
        record["failures"] = max(failures) if failures else None
    if arm == "lint":
        match = LINT_SUMMARY.search(log)
        if match:
            record["problems"] = int(match.group(1))
            record["errors"] = int(match.group(2))
            record["warnings"] = int(match.group(3))
        else:
            record["problems"] = None
    if arm == "types":
        record["errors"] = len(TSC_ERROR.findall(log))
    if arm in {"docs", "gnn"}:
        summary = [line for line in log.splitlines() if FINAL_SUMMARY.search(line)]
        record["summary"] = summary[-1].strip() if summary else ""
    return record


def render(records: list[dict[str, object]], root: Path) -> str:
    node = tool_version(["node", "--version"])
    npm = tool_version(["npm", "--version"])
    python = tool_version([sys.executable, "--version"])
    head = subprocess.run(
        ["git", "-C", str(root), "rev-parse", "--short=12", "HEAD"],
        capture_output=True,
        text=True,
        check=False,
    ).stdout.strip()
    # This document is written by this script; its own pending change does not
    # make the measured tree dirty.
    status = subprocess.run(
        ["git", "-C", str(root), "status", "--porcelain"],
        capture_output=True,
        text=True,
        check=False,
    ).stdout.splitlines()
    others = [
        line
        for line in status
        if not line.rstrip().endswith("Docs/GATE_METRICS.md")
    ]
    tree_state = "clean" if not others else f"{len(others)} uncommitted path(s) besides this document"

    lines = [
        "# Gate metrics",
        "",
        "<!-- generated by scripts/gate_metrics.py; refresh with `./run.sh metrics` -->",
        "",
        "Measured by running each arm once on this host. Timings are wall clock for",
        "the whole arm, including the runner's own overhead; they are observations,",
        "not targets. Arms marked **known red** are reported, not enforced — see",
        "[`RUN_GUIDE.md`](RUN_GUIDE.md#known-red-checks).",
        "",
        f"- source revision: `{head or 'unknown'}` ({tree_state})",
        f"- host: {platform.platform()} ({platform.machine()})",
        f"- node {node} · npm {npm} · {python}",
        f"- measured: {time.strftime('%Y-%m-%d %H:%M:%S %Z')}",
        "",
        "| Arm | Kind | Wall time (s) | Exit | Result |",
        "| --- | --- | --- | --- | --- |",
    ]

    for record in records:
        arm = str(record["arm"])
        kind = dict((name, k) for name, k, _ in ARMS)[arm]
        detail = ""
        if "failures" in record and record["failures"] is not None:
            detail = f"failures: {record['failures']}"
        if arm == "lint" and record.get("problems") is not None:
            detail = f"{record['problems']} problems ({record['errors']} errors, {record['warnings']} warnings)"
        if arm == "types" and record.get("errors") is not None:
            detail = f"{record['errors']} type errors"
        if record.get("summary"):
            detail = str(record["summary"])
        status = "pass" if record["exit"] == 0 else f"**fail** ({detail})"
        if record["exit"] == 0 and detail:
            status = f"pass ({detail})"
        lines.append(
            f"| `{arm}` | {kind} | {record['seconds']} | {record['exit']} | {status} |"
        )

    fast = next((r for r in records if r["arm"] == "fast"), None)
    if fast and fast.get("tests"):
        lines.extend(["", "## Test counts", "", "| Subset | Tests |", "| --- | --- |"])
        for suite, count in sorted(dict(fast["tests"]).items()):
            lines.append(f"| {suite} | {count} |")

    lines.extend(
        [
            "",
            "## Arms",
            "",
            "| Arm | Command | What it proves |",
            "| --- | --- | --- |",
            "| `fast` | `./run.sh fast` | the three credential-free harness subsets pass and report `Failed: 0` |",
            "| `build` | `./run.sh build` | the DE bundle builds and `dist/KG` carries every document and publication record |",
            "| `website` | `./run.sh website` | the Next.js site builds, including its own TypeScript step |",
            "| `docs` | `./run.sh docs` | every relative Markdown link and anchor resolves, with exact case |",
            "| `gnn` | `./run.sh gnn` | the pinned parser version parses and type-checks the conformance target |",
            "| `lint` | `./run.sh lint` | ESLint findings in DE/ (**known red**) |",
            "| `types` | `./run.sh types` | `tsc -b` findings in DE/ (**known red**) |",
            "",
        ]
    )
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument(
        "--only",
        action="append",
        choices=[name for name, _, _ in ARMS],
        help="measure only the named arm(s); the document still needs every arm to be complete",
    )
    args = parser.parse_args(argv)

    root = args.root.resolve()
    if not (root / "run.sh").is_file():
        raise SystemExit(f"{root}/run.sh not found")
    if shutil.which("git") is None:
        raise SystemExit("git is required to record the source revision")

    selected = [(name, kind, doc) for name, kind, doc in ARMS if not args.only or name in args.only]
    log_dir = root / ".gate" / "metrics"
    records = [run_arm(arm, root, log_dir) for arm, _, _ in selected]

    document = render(records, root)
    target = root / "Docs" / "GATE_METRICS.md"
    target.write_text(document + "\n", encoding="utf-8")
    print(document)

    failed = [r["arm"] for r in records if r["exit"] != 0]
    if failed:
        print(f"\nmeasured; non-zero arms: {', '.join(str(a) for a in failed)}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
